"""
Citation Verifier Module for StudentAI Advanced RAG.
Verifies factual citations and page references generated by LLM models against retrieved context chunks:
- Validates that cited pages ([Page X]) exist in the retrieved context passages.
- Validates that cited documents correspond to retrieved document sources.
- Detects malformed citation syntaxes.
- Distinguishes format validity from semantic grounding.
- Exposes structured verification results with explicit errors and warnings.
"""

from typing import Dict, Any, List, Set, Optional
import re
from src.context_builder import extract_page_citations


def verify_citations(
    answer: str,
    sources: List[Dict[str, Any]],
    expected_documents: Optional[List[str]] = None,
) -> Dict[str, Any]:
    """
    Verifies that all page citations in the answer exist in the retrieved sources.

    Args:
        answer: Generated text containing citations (e.g. "... [Page 1]").
        sources: List of retrieved chunk dictionaries used as context.
        expected_documents: Optional list of expected document names to check against.

    Returns:
        Structured citation verification report:
        {
            "is_valid": bool,
            "cited_pages": List[int],
            "valid_pages": List[int],
            "invalid_pages": List[int],
            "retrieved_pages": List[int],
            "retrieved_documents": List[str],
            "malformed_citations": List[str],
            "has_citations": bool,
            "errors": List[str],
            "warnings": List[str],
        }
    """
    if not answer or not answer.strip():
        return {
            "is_valid": True,
            "cited_pages": [],
            "valid_pages": [],
            "invalid_pages": [],
            "retrieved_pages": [],
            "retrieved_documents": [],
            "malformed_citations": [],
            "has_citations": False,
            "errors": [],
            "warnings": ["Answer is empty."],
        }

    # Extract all cited pages
    cited_pages = extract_page_citations(answer)

    # Detect malformed citation patterns (e.g., [page], [page -1], [Page abc], (Page 1))
    malformed: List[str] = []
    # Check for [page without number]
    for match in re.findall(r"\[page\s*\]", answer, re.IGNORECASE):
        malformed.append(match)
    # Check for non-numeric like [Page X] where X is not an int
    for match in re.findall(r"\[Page\s+([a-zA-Z]+)\]", answer):
        malformed.append(f"[Page {match}]")

    # Collect all pages and documents actually retrieved
    retrieved_pages: Set[int] = set()
    retrieved_docs: Set[str] = set()

    for s in (sources or []):
        p_num = s.get("page_number")
        if p_num is not None:
            try:
                retrieved_pages.add(int(p_num))
            except (ValueError, TypeError):
                pass
        fn = s.get("file_name")
        if fn:
            retrieved_docs.add(fn.strip().lower())

    valid_pages = [p for p in cited_pages if p in retrieved_pages]
    invalid_pages = [p for p in cited_pages if p not in retrieved_pages]

    errors: List[str] = []
    warnings: List[str] = []

    if malformed:
        errors.append(f"Malformed citation syntax detected: {', '.join(malformed)}")

    if invalid_pages:
        errors.append(
            f"Answer cites pages not present in retrieved context: {invalid_pages} "
            f"(Retrieved pages: {sorted(list(retrieved_pages))})"
        )

    # If answer is not a refusal and contains factual statements without citations
    standard_refusal = "couldn't find the answer" in answer.lower()
    if not standard_refusal and not cited_pages:
        warnings.append("Answer contains no [Page X] citations.")

    # Check expected documents if supplied
    if expected_documents:
        expected_set = {d.strip().lower() for d in expected_documents}
        missing_docs = expected_set - retrieved_docs
        if missing_docs:
            warnings.append(f"Expected source documents missing from retrieved context: {list(missing_docs)}")

    is_valid = len(errors) == 0

    return {
        "is_valid": is_valid,
        "cited_pages": cited_pages,
        "valid_pages": valid_pages,
        "invalid_pages": invalid_pages,
        "retrieved_pages": sorted(list(retrieved_pages)),
        "retrieved_documents": sorted(list(retrieved_docs)),
        "malformed_citations": malformed,
        "has_citations": len(cited_pages) > 0,
        "errors": errors,
        "warnings": warnings,
    }
